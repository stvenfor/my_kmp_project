// 构建期环境 / 版本单一真源 → 生成 :core:network 的 BuildEnvironment.kt。
//
// 由 :core:network/build.gradle.kts 通过 apply(from = ...) 引入；只在该模块生成，
// 避免同一个 FQN 出现在多个模块里造成重复类。
//
// 读取顺序：-P<key> > 环境变量 > gradle/app.env.properties > 内置默认值。
// 所有输入都通过 Provider 读取，配置缓存可感知 app.env.properties 的变化。
//
// 注意：apply(from=...) 的脚本 classpath 上没有 KGP 类型，所以这里不直接配置
// kotlin.sourceSets；任务与目录通过 extra 暴露，由模块自己的 build.gradle.kts 接线。
import java.util.Properties

val appEnvFileText: Provider<String> = providers.fileContents(
    rootProject.layout.projectDirectory.file("gradle/app.env.properties"),
).asText.orElse("")

val appEnvFileEntries: Provider<Map<String, String>> = appEnvFileText.map { text ->
    Properties().apply { text.reader().use { load(it) } }
        .entries
        .associate { (key, value) -> key.toString() to value.toString() }
}

fun appEnvFileValue(key: String, fallback: String): Provider<String> =
    appEnvFileEntries.map { entries ->
        entries[key]?.takeIf { it.isNotBlank() } ?: fallback
    }

fun appEnvOverride(property: String, envName: String): Provider<String> =
    providers.gradleProperty(property).orElse(providers.environmentVariable(envName))

fun appEnvValue(property: String, envName: String, fileKey: String, fallback: String): String =
    appEnvOverride(property, envName).orElse(appEnvFileValue(fileKey, fallback)).get().trim()

fun appEnvNormalize(raw: String): String = when (raw.trim().lowercase()) {
    "dev", "debug" -> "dev"
    "test" -> "test"
    "staging", "stage" -> "staging"
    "prod", "production", "release" -> "prod"
    else -> throw GradleException(
        "Unknown app.env '$raw' (expected: dev | test | staging | prod)",
    )
}

/** 生成 Kotlin 字符串字面量（转义反斜杠、引号、$ 与换行）。 */
fun appEnvLiteral(value: String): String {
    val escaped = buildString {
        value.forEach { ch ->
            when (ch) {
                '\\' -> { append('\\'); append('\\') }
                '"' -> { append('\\'); append('"') }
                '$' -> { append('\\'); append('$') }
                '\n' -> { append('\\'); append('n') }
                '\r' -> { append('\\'); append('r') }
                else -> append(ch)
            }
        }
    }
    return "\"$escaped\""
}

val appIsRelease: Boolean =
    appEnvOverride("app.release", "APP_RELEASE").orElse("false").get().toBoolean()

val appBuildEnv: String = appEnvNormalize(
    appEnvOverride("app.env", "APP_ENV")
        .orElse(if (appIsRelease) "prod" else "dev")
        .get(),
)

val appVersionName: String =
    appEnvValue("app.versionName", "APP_VERSION_NAME", "version.name", "1.0")

val appVersionCode: Int =
    appEnvValue("app.versionCode", "APP_VERSION_CODE", "version.code", "1")
        .toIntOrNull()
        ?: throw GradleException("app.versionCode must be an integer")

val appHostDev: String =
    appEnvValue("app.hosts.dev", "APP_HOST_DEV", "host.dev", "http://127.0.0.1:8080")
val appHostTest: String =
    appEnvValue("app.hosts.test", "APP_HOST_TEST", "host.test", "http://127.0.0.1:8080")
val appHostStaging: String =
    appEnvValue("app.hosts.staging", "APP_HOST_STAGING", "host.staging", "http://127.0.0.1:8080")
val appHostProd: String =
    appEnvValue("app.hosts.prod", "APP_HOST_PROD", "host.prod", "https://api.xiaomaomain.com")

val generatedBuildEnvDir: Provider<Directory> =
    layout.buildDirectory.dir("generated/buildEnvironment/commonMain/kotlin")

val generatedBuildEnvSource: String = """
    package com.example.my_kmp_project.core.network

    // Generated by :core:network:generateBuildEnvironment — do not edit.
    // Source of truth: gradle/app.env.properties + -Papp.* / APP_* overrides.
    public object BuildEnvironment {
        public const val ENV: String = ${appEnvLiteral(appBuildEnv)}
        public const val IS_RELEASE: Boolean = $appIsRelease
        public const val VERSION_NAME: String = ${appEnvLiteral(appVersionName)}
        public const val VERSION_CODE: Int = $appVersionCode

        public const val API_DEV: String = ${appEnvLiteral(appHostDev)}
        public const val API_TEST: String = ${appEnvLiteral(appHostTest)}
        public const val API_STAGING: String = ${appEnvLiteral(appHostStaging)}
        public const val API_PROD: String = ${appEnvLiteral(appHostProd)}

        public fun environment(): NetEnvironment = when (ENV) {
            "dev" -> NetEnvironment.Dev
            "test" -> NetEnvironment.Test
            "staging" -> NetEnvironment.Staging
            "prod" -> NetEnvironment.Product
            else -> NetEnvironment.Product
        }

        public fun apiHostFor(environment: NetEnvironment): String = when (environment) {
            NetEnvironment.Dev -> API_DEV
            NetEnvironment.Test -> API_TEST
            NetEnvironment.Staging -> API_STAGING
            NetEnvironment.Product, NetEnvironment.Custom -> API_PROD
        }
    }
""".trimIndent() + "\n"

val generateBuildEnvironment = tasks.register("generateBuildEnvironment") {
    // 先取到局部变量，避免 doLast 闭包捕获脚本对象（配置缓存不允许）。
    val outputDirProvider = generatedBuildEnvDir
    val sourceText = generatedBuildEnvSource

    group = "build"
    description = "Generate core/network BuildEnvironment.kt from gradle/app.env.properties."
    inputs.property("env", appBuildEnv)
    inputs.property("release", appIsRelease)
    inputs.property("versionName", appVersionName)
    inputs.property("versionCode", appVersionCode)
    inputs.property("hostDev", appHostDev)
    inputs.property("hostTest", appHostTest)
    inputs.property("hostStaging", appHostStaging)
    inputs.property("hostProd", appHostProd)
    outputs.dir(outputDirProvider)

    doLast {
        val target = outputDirProvider.get().asFile
            .resolve("com/example/my_kmp_project/core/network/BuildEnvironment.kt")
        if (!target.isFile || target.readText() != sourceText) {
            target.parentFile.mkdirs()
            target.writeText(sourceText)
        }
    }
}

extensions.extraProperties.set("buildEnvironmentTask", generateBuildEnvironment)
extensions.extraProperties.set("buildEnvironmentDir", generatedBuildEnvDir)
