#!/usr/bin/env python3
"""Deep-dive doc acceptance gate: citation truthfulness + scope coverage."""
import json
import os
import re
import sys

ROOT = "/Users/qpy/Desktop/github/my_kmp_project"
DOC_DIR = os.path.join(ROOT, "docs/deep-dive")
EXTERNAL_ROOTS = {"my_ai_project": "/Users/qpy/Desktop/github/my_ai_project"}

MANIFEST = json.load(open(os.path.join(DOC_DIR, "_verify/manifest.json")))

CITE_RE = re.compile(
    r"([\w./\-]+\.(?:kt|kts|swift|ets|json|json5|yaml|yml|md|sh|py|toml|properties|xml|html|def|c|h))"
    r"\s*[:：]\s*(\d{1,6})(?:\s*[-–]\s*(\d{1,6}))?"
)

linecount_cache = {}

GEN_OK = {"Res.kt"}  # generated by the Compose resources plugin, not a source file
_repo_index = None


def repo_index():
    global _repo_index
    if _repo_index is None:
        _repo_index = []
        for dirpath, dirnames, filenames in os.walk(ROOT):
            dirnames[:] = [x for x in dirnames if x not in ("build", ".git", ".gradle", "node_modules", "oh_modules", ".hvigor")]
            for fn in filenames:
                _repo_index.append(os.path.relpath(os.path.join(dirpath, fn), ROOT))
    return _repo_index


def resolve(rel):
    """Resolve a possibly-abbreviated/bare/suffix citation path. Returns rel path or None.

    A `my_ai_project/...` prefix addresses the Flutter SoT repo next door."""
    for name, root in EXTERNAL_ROOTS.items():
        pre = name + "/"
        if rel.startswith(pre) and os.path.exists(os.path.join(root, rel[len(pre):])):
            return os.path.join(root, rel[len(pre):])
    rel_clean = rel.lstrip("./").replace("…", "").replace(".../", "").replace("...", "")
    if os.path.exists(os.path.join(ROOT, rel_clean)):
        return rel_clean
    base = os.path.basename(rel_clean)
    if base in GEN_OK:
        return None
    index = repo_index()
    exact = [p for p in index if os.path.basename(p) == base]
    if len(exact) == 1:
        return exact[0]
    # citation may be a suffix of the real basename (e.g. "coil.kt" for "X.coil.kt")
    suffix = [p for p in index if os.path.basename(p).endswith(base) and os.path.basename(p) != base]
    if len(suffix) == 1:
        return suffix[0]
    # match on trailing directory components
    if len(exact) > 1:
        parts = [p for p in exact if all(seg in p for seg in rel_clean.split("/")[:-1] if seg)]
        if len(parts) == 1:
            return parts[0]
    return None


def line_count(path):
    if path not in linecount_cache:
        try:
            with open(path, "rb") as fh:
                linecount_cache[path] = fh.read().count(b"\n") + 1
        except OSError:
            linecount_cache[path] = None
    return linecount_cache[path]


def scope_files(spec):
    out = []
    for d in spec.get("dirs", []):
        base = os.path.join(ROOT, d)
        if not os.path.isdir(base):
            out.append(("MISSING_DIR:" + d, True))
            continue
        for dirpath, dirnames, filenames in os.walk(base):
            dirnames[:] = [x for x in dirnames if x != "build"]
            for fn in filenames:
                if fn.endswith((".kt", ".kts", ".swift", ".ets", ".sh", ".py", ".def")):
                    out.append((os.path.relpath(os.path.join(dirpath, fn), ROOT), False))
    for f in spec.get("files", []):
        out.append((f, not os.path.exists(os.path.join(ROOT, f))))
    return sorted(set(out))


LEGEND_RE = re.compile(r"\|\s*`<([A-Za-z0-9_.-]+)>`[^|]*\|\s*`([^`]+)`\s*\|")


def legend(text):
    """Path macros defined in a glossary table, e.g. `<FM>` -> feature/media/..."""
    out = {}
    for k, v in LEGEND_RE.findall(text):
        out["<%s>" % k] = v.rstrip("/")
    return out


def expand(rel, leg):
    for tok, real in leg.items():
        if rel.startswith(tok):
            return real + rel[len(tok):]
        if rel == tok:
            return real
    return rel


def check_doc(name, spec):
    path = os.path.join(DOC_DIR, name)
    res = {"doc": name, "exists": os.path.exists(path)}
    if not res["exists"]:
        res["verdict"] = "FAIL-missing"
        return res
    text = open(path, encoding="utf-8").read()
    res["lines"] = text.count("\n") + 1
    res["h2"] = len(re.findall(r"(?m)^## ", text))
    res["tables"] = text.count("|---") + text.count("| ---") + text.count("| :-")

    leg = legend(text)
    bad, checked, ambiguous = [], 0, 0
    for m in CITE_RE.finditer(text):
        rel, ln, ln2 = m.group(1), int(m.group(2)), m.group(3)
        resolved = resolve(expand(rel, leg))
        if resolved is None:
            if os.path.basename(rel.lstrip("./")) in GEN_OK:
                continue
            bad.append(("path-not-found", rel, ln))
            continue
        if resolved != rel.lstrip("./"):
            ambiguous += 1
        lc = line_count(resolved if os.path.isabs(resolved) else os.path.join(ROOT, resolved))
        checked += 1
        hi = int(ln2) if ln2 else ln
        if lc is None or hi > lc:
            bad.append(("line-out-of-range", resolved, "%s(%s lines)" % (hi, lc)))
    res["citations_checked"] = checked
    res["citations_abbreviated"] = ambiguous
    res["citations_bad"] = bad[:12]
    res["citations_bad_count"] = len(bad)

    files = scope_files(spec)
    res["scope_missing_dir"] = [x for x, miss in files if miss]
    res["scope_total"] = len(files)
    return res


def main():
    names = sys.argv[1:] or list(MANIFEST)
    results = []
    for name in names:
        spec = MANIFEST.get(name)
        if not spec:
            results.append({"doc": name, "verdict": "FAIL-not-in-manifest"})
            continue
        r = check_doc(name, spec)
        if not r.get("exists"):
            r["verdict"] = "FAIL-missing"
        else:
            r["verdict"] = "PASS" if (
                r.get("lines", 0) >= 200 and r.get("h2", 0) >= 5
                and r.get("citations_bad_count", 0) == 0 and not r.get("scope_missing_dir")
            ) else "REVIEW"
        results.append(r)

    texts = {}
    for name in names:
        p = os.path.join(DOC_DIR, name)
        if os.path.exists(p):
            texts[name] = open(p, encoding="utf-8").read()

    # coverage: each scope file's basename must appear in its doc (or the shared pair)
    for r in results:
        name = r["doc"]
        spec = MANIFEST.get(name)
        if not spec or not r.get("exists"):
            continue
        blob = texts.get(name, "")
        if spec.get("shared_with"):
            blob = blob + texts.get(spec["shared_with"], "")
        miss = []
        for rel, _ in scope_files(spec):
            if rel.startswith("MISSING_DIR:"):
                continue
            if os.path.basename(rel) not in blob:
                miss.append(rel)
        r["coverage_unmentioned"] = miss
        r["coverage_mentioned"] = r.get("scope_total", 0) - len(miss)
        if miss:
            r["verdict"] = "REVIEW"

    for r in results:
        print("%-46s %-8s lines=%-5s h2=%-3s cite=%-5s abbrev=%-4s bad=%-3s cov=%s/%s" % (
            r["doc"], r["verdict"], r.get("lines", 0), r.get("h2", 0),
            r.get("citations_checked", 0), r.get("citations_abbreviated", 0),
            r.get("citations_bad_count", 0),
            r.get("coverage_mentioned", "-"), r.get("scope_total", "-")))
        for kind, rel, ln in r.get("citations_bad", []):
            print("    BAD-CITE %-16s %s:%s" % (kind, rel, ln))
        for m in r.get("scope_missing_dir", []):
            print("    MISSING-DIR %s" % m)
        um = r.get("coverage_unmentioned", [])
        if um:
            print("    UNMENTIONED(%d): %s" % (len(um), ", ".join(um[:10])))
    print()
    print("summary:", ", ".join("%s=%s" % (r["doc"][:2], r["verdict"]) for r in results))


if __name__ == "__main__":
    main()
